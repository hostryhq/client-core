#!/usr/bin/env python3
"""Generates the restaurant entity schemas and the intent registry from api-specs.

    python3 -I scripts/gen-sync-registry.py [API_SPECS_DIR]

Writes src/sync/restaurant.generated.ts and src/ops/intents.generated.ts. Never edit those by hand.
Needs PyYAML (generator only; nothing at runtime).
"""
import json
import os
import subprocess
import sys

import yaml

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
specs = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("API_SPECS_DIR", os.path.join(root, "..", "api-specs")))
try:
    sha = subprocess.run(["git", "-C", specs, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip() or "unknown"
except OSError:
    sha = "unknown"
HEADER = "// GENERATED by scripts/gen-sync-registry.py from api-specs@%s. Do not edit; regenerate.\n" % sha


def ts(v):
    return json.dumps(v, indent=2, sort_keys=False, ensure_ascii=False)


# ---- entities -----------------------------------------------------------------------------------
ents = []
edir = os.path.join(specs, "entities", "restaurant")
for fn in sorted(os.listdir(edir)):
    if not fn.endswith(".yaml"):
        continue
    with open(os.path.join(edir, fn), encoding="utf-8") as fh:
        d = yaml.safe_load(fh)
    fields = {}
    for name, f in (d.get("fields") or {}).items():
        r = {"policy": f.get("policy", "immutable")}
        if f.get("order"):
            r["order"] = f["order"]
        if f.get("pii"):
            r["pii"] = True
        fields[name] = r
    e = {"name": d["entity"], "owner": d.get("owner"), "stream": d.get("stream"), "policy": d["policy"], "id": d.get("id", {})}
    if d.get("tombstone"):
        e["deletable"] = True
    if d.get("guarded"):
        e["guarded"] = True
    if any(f.get("doc_number") for f in (d.get("fields") or {}).values()):
        e["docNumber"] = True
    e["fields"] = fields
    ents.append(e)

with open(os.path.join(root, "src", "sync", "restaurant.generated.ts"), "w", encoding="utf-8") as out:
    out.write(HEADER)
    out.write('import type { EntityDef } from "./restaurant";\n\n')
    out.write("export const RESTAURANT_ENTITY_DEFS: EntityDef[] = %s;\n" % ts(ents))

# ---- intents ------------------------------------------------------------------------------------
intents = {}
idir = os.path.join(specs, "sync", "intents")
for fn in sorted(os.listdir(idir)):
    if not fn.endswith(".yaml"):
        continue
    with open(os.path.join(idir, fn), encoding="utf-8") as fh:
        d = yaml.safe_load(fh)
    for i in d.get("intents", []):
        intents[i["intent"]] = {
            "v": i["intent_v"],
            "class": i["class"],
            "owner": i.get("owner"),
            "permission": i.get("permission"),
            "proof": (i.get("proof") or {}).get("kind"),
            "binds": (i.get("proof") or {}).get("binds", []),
            "override": bool(i.get("override")),
            "sessions": i.get("sessions", []),
            "deviceKinds": i.get("device_kinds", []),
            "streams": i.get("streams", []),
            "numbering": i.get("numbering", "none"),
            "documents": i.get("documents", []),
            "entities": i.get("entities") or {},
            "records": i.get("records") or [],
        }
with open(os.path.join(root, "src", "ops", "intents.generated.ts"), "w", encoding="utf-8") as out:
    out.write(HEADER)
    out.write('import type { IntentDef } from "./intents";\n\n')
    out.write("export const INTENT_DEFS: Record<string, IntentDef> = %s;\n" % ts(intents))
print("entities: %d, intents: %d (api-specs@%s)" % (len(ents), len(intents), sha))
