const PHONE = "+919800011122";
const NAME = "Asha Raman";
const wireOf = (v: PiiWire | undefined): Record<string, unknown> => v?.order?.o1 ?? {};

/** svc-sync `syncproto.CommitPII` golden vectors (generated by the Go code with a fixed salt; Go checks the same construction). */
describe("pii commitments match svc-sync byte for byte", () => {
  it("SHA-256(salt || JCS(value)) for strings, booleans, integers, unicode and escapes", async () => {
    for (const [i, v] of vectors.entries()) {
      const r = await commitPii({ e: { r: { f: v.value } } }, (n) => new Uint8Array(n).fill(i + 1));
      expect(r!.wire.e!.r![PII_SALT_PREFIX + "f"]).toBe(v.salt_b64u);
      expect(r!.commits.e!.r!.f).toBe(v.c);
    }
  });

  it("a value that is not a string, boolean or integer is refused", async () => {
    await expect(commitPii({ e: { r: { f: 1.5 } } })).rejects.toThrow(/integer/);
    await expect(commitPii({ e: { r: { f: { a: 1 } } } })).rejects.toThrow(/integer/);
    await expect(commitPii({ e: { r: { "~s:f": "x" } } })).rejects.toThrow(/reserved/);
  });

  it("two commitments of one value differ (random salt) and the body names no value", async () => {
    const a = await commitPii({ e: { r: { f: PHONE } } });
    const b = await commitPii({ e: { r: { f: PHONE } } });
    expect(a!.commits.e!.r!.f).not.toBe(b!.commits.e!.r!.f);
    expect(JSON.stringify(a!.commits)).not.toContain("9800011122");
  });
});

async function author(): Promise<{ w: Awaited<ReturnType<typeof makeWorld>>; a: Device; rx: Device }> {
  const w = await makeWorld();
  const a = await w.addDevice("devA", { withHub: false });
  const rx = await w.addDevice("rx", { withHub: false });
  await a.engine.record({
    intent: "order.create",
    pii: { order: { o1: { customer_phone: PHONE, customer_name: NAME } } },
    build: () => [{ e: "order", id: "o1", k: "insert", f: { table: "T1" } }],
  });
  return { w, a, rx };
}

describe("pii commitments in the sealed body", () => {
  it("the body carries commitments only; the wire pii carries values and salts; the hash covers the commitments", async () => {
    const { a } = await author();
    const [it] = (await authorBatch(a)).items;
    const op = JSON.parse(it!.body!) as OpEnvelope;
    expect(it!.body).not.toContain(PHONE);
    expect(it!.body).not.toContain(NAME);
    expect(Object.keys(op.pii_c!.order!.o1!).sort()).toEqual(["customer_name", "customer_phone"]);
    const w = wireOf(it!.pii as PiiWire);
    expect(w.customer_phone).toBe(PHONE);
    expect(typeof w[PII_SALT_PREFIX + "customer_phone"]).toBe("string");
  });

  it("a receiver keeps verified fields and drops a changed value, a missing salt and a field with no commitment", async () => {
    const { a, rx } = await author();
    const batch = await authorBatch(a);
    const it = batch.items[0]!;
    const bad = structuredClone(it.pii as PiiWire);
    bad.order!.o1!.customer_phone = "+911111111111"; // value changed in transit
    delete bad.order!.o1![PII_SALT_PREFIX + "customer_name"]; // salt stripped
    bad.order!.o1!.extra = "x"; // no commitment
    bad.order!.o1![PII_SALT_PREFIX + "extra"] = b64url(new Uint8Array(16));
    expect((await rx.engine.applyRemote(OUTLET, [{ ...it, pii: bad }], batch.seals)).applied).toBe(1);
    const kept = await openPii(bad, (JSON.parse(it.body!) as OpEnvelope).pii_c);
    expect(kept.dropped).toBe(3);
    expect(kept.values).toBeUndefined();
    const onRx = (await rx.engine.outbox(OUTLET, {}, "all", 100)).items[0]!;
    expect(onRx.pii).toBeUndefined(); // nothing unverifiable is stored, so nothing is relayed
  });

  it("verified pii is stored, with salts, and relayed on", async () => {
    const { a, rx } = await author();
    const batch = await authorBatch(a);
    await rx.engine.applyRemote(OUTLET, batch.items, batch.seals);
    const onRx = (await rx.engine.outbox(OUTLET, {}, "all", 100)).items[0]!;
    expect(wireOf(onRx.pii as PiiWire).customer_phone).toBe(PHONE);
    expect(wireOf(onRx.pii as PiiWire)[PII_SALT_PREFIX + "customer_phone"]).toBeDefined();
  });
});

/** Everything this device holds in the store, as text: sync tables and entity tables. */
async function dump(d: Device): Promise<string> {
  const tables = [...Object.values(T), "order"];
  const rows = await Promise.all(tables.map((t) => d.store.list(t)));
  return JSON.stringify(rows);
}

describe("cloud-signed pii erasure (sync.pii.erase)", () => {
  it("no erased value survives on the author, a pulling device, or in what either relays; commitments stay; the chain still verifies", async () => {
    const { w, a, rx } = await author();
    await w.syncDevice(a);
    await w.syncDevice(rx);
    expect(await dump(rx)).toContain(PHONE);
    const ref: OpRef = { origin: "devA", stream: OUTLET, seq: 1 };
    await w.cloud.erasePii(ref);
    // The erased op is applied before the next hello: the cloud no longer holds the values either.
    await w.syncDevice(rx);
    await w.syncDevice(a);
    for (const d of [a, rx]) {
      const text = await dump(d);
      expect(text).not.toContain(PHONE);
      expect(text).not.toContain(NAME);
      expect(text).not.toContain("~s:customer_phone");
      const out = JSON.stringify((await d.engine.outbox(OUTLET, {}, "all", 100)).items);
      expect(out).not.toContain(PHONE);
      expect(out).toContain('\\"pii_c\\"'); // the sealed body, with its commitments, is intact
    }
    expect((await rx.engine.vector()).devA).toBe(1);
  });

  it("a late arrival of the pii after the erasure is discarded", async () => {
    const { w, a, rx } = await author();
    await w.syncDevice(a);
    const batch = await authorBatch(a);
    await w.cloud.erasePii({ origin: "devA", stream: OUTLET, seq: 1 });
    await w.syncDevice(rx); // gets the erased op and the erasure
    await rx.engine.applyRemote(OUTLET, batch.items, batch.seals); // a stale peer re-offers the values
    expect(await dump(rx)).not.toContain(PHONE);
  });

  it("acknowledges the erasure in the next direct cloud hello, once, and not to a hub", async () => {
    const { w, a, rx } = await author();
    await w.syncDevice(a);
    await w.syncDevice(rx);
    const ref: OpRef = { origin: "devA", stream: OUTLET, seq: 1 };
    await w.cloud.erasePii(ref);
    await w.syncDevice(rx); // applies the erasure; its hello preceded it
    expect(await rx.engine.pendingErasureAcks()).toEqual([ref]);
    await w.syncDevice(rx); // next direct cloud hello carries the acknowledgement
    const sent = w.cloud.hellos.filter((h) => h.pii_erased?.length);
    expect(sent).toHaveLength(1);
    expect(sent[0]!.pii_erased).toEqual([ref]);
    expect(await rx.engine.pendingErasureAcks()).toEqual([]);
    await w.syncDevice(rx);
    expect(w.cloud.hellos.filter((h) => h.pii_erased?.length)).toHaveLength(1);
  });

  it("an erasure op not signed by the cloud erases nothing", async () => {
    const w = await makeWorld();
    const a = await w.addDevice("devA", { withHub: false, schemas: new SchemaRegistry([...DEMO_SCHEMAS, { name: "pii_erase", policy: "append" }]) });
    const rx = await w.addDevice("rx", { withHub: false });
    await a.engine.record({ intent: "order.create", pii: { order: { o1: { customer_phone: PHONE } } }, build: () => [{ e: "order", id: "o1", k: "insert", f: {} }] });
    await a.engine.recordMuts("order.create", [{ e: "pii_erase", id: `${OUTLET}|devA|1`, k: "insert", f: { origin: "devA", stream: OUTLET, seq: 1 } }]);
    const batch = await authorBatch(a);
    await rx.engine.applyRemote(OUTLET, batch.items, batch.seals);
    expect(await dump(rx)).toContain(PHONE);
  });
});

describe("erasure reaches rows, field candidates, conflict records and the print spool", () => {
  const check = (id: string, f: Record<string, unknown>, k: "insert" | "set" = "insert") => [{ e: "check", id, k, f }];

  it("erasing one op removes its values from rows and candidates; erasing the other leaves no value anywhere", async () => {
    const w = await makeWorld();
    const a = await w.addDevice("devA", { withHub: false, schemas: restaurantRegistry() });
    const rx = await w.addDevice("rx", { withHub: false, schemas: restaurantRegistry() });
    await a.engine.recordMuts("check.create", check("c1", { order_type: "dine_in", status: "open", customer_name: "First Name" }));
    await a.engine.recordMuts("bill.customer_details.edit", check("c1", { customer_name: "Second Name", customer_phone: "+910000000001" }, "set"));
    await w.syncDevice(a);
    await w.syncDevice(rx);
    expect((await rx.engine.rows("check"))[0]).toMatchObject({ customer_name: "Second Name" });

    await w.cloud.erasePii({ origin: "devA", stream: OUTLET, seq: 2 });
    await w.syncDevice(rx);
    await w.syncDevice(a);
    for (const d of [a, rx]) {
      const row = (await d.engine.rows("check"))[0]!;
      expect(row.customer_name).not.toBe("Second Name"); // the earlier value may have been trimmed once the later one was confirmed
      expect(row.customer_phone).toBeUndefined();
      const text = JSON.stringify([await d.store.list("check"), await d.store.list(T.op)]);
      expect(text).not.toContain("Second Name");
      expect(text).not.toContain("+910000000001");
    }
    await w.cloud.erasePii({ origin: "devA", stream: OUTLET, seq: 1 });
    await w.syncDevice(rx);
    await w.syncDevice(a);
    for (const d of [a, rx]) {
      expect((await d.engine.rows("check"))[0]!.customer_name).toBeUndefined();
      expect(JSON.stringify([await d.store.list("check"), await d.store.list(T.op)])).not.toContain("First Name");
    }
  });

  it("tells the app what was erased so it can purge its print spool", async () => {
    const w = await makeWorld();
    const seen: string[] = [];
    const a = await w.addDevice("devA", { withHub: false, schemas: restaurantRegistry() });
    const rx = await w.addDevice("rx", { withHub: false, schemas: restaurantRegistry() });
    // Reopen rx with a listener (a process restart over the same store).
    const { SyncEngine } = await import("./engine");
    const eng = await SyncEngine.open({
      store: rx.store, schemas: restaurantRegistry(), deviceId: "rx", outletStream: OUTLET, streams: [OUTLET], signer: rx.signer, verifier: w.ring, packVersion: 1, now: w.clock.now,
      onPiiErased: (e) => seen.push(...piiStrings(e.values)),
    });
    eng.session = { actor: "m1", sid: "s-rx" };
    await a.engine.recordMuts("check.create", check("c1", { order_type: "dine_in", status: "open", customer_name: "Spool Person" }));
    await w.syncDevice(a); // the cloud holds the op
    const batch = await authorBatch(a);
    await eng.applyRemote(OUTLET, batch.items, batch.seals);
    const erasure = await w.cloud.erasePii({ origin: "devA", stream: OUTLET, seq: 1 }); // cloud op seals itself
    void erasure;
    const cb = await cloudBatch(w.cloud);
    await eng.applyRemote(OUTLET, cb.items, cb.seals);
    expect(seen).toEqual(["Spool Person"]);

    const svc = new PrintService();
    const q = svc.addPrinter("p1", { width: 42 } as never, () => Promise.reject(new Error("offline")));
    q.enqueue("j1", new TextEncoder().encode("TOTAL\nSpool Person\n"), "bill");
    q.enqueue("j2", new TextEncoder().encode("KOT 4\n"), "kot");
    expect(svc.purgeStrings(seen)).toBe(1);
    expect(q.pending().map((j) => j.id)).toEqual(["j2"]);
  });

  it("customer_gstin on a check and a bill is personal data: erased on the author and a pulling device (soak X2)", async () => {
    const w = await makeWorld();
    const a = await w.addDevice("devA", { withHub: false, schemas: restaurantRegistry() });
    const rx = await w.addDevice("rx", { withHub: false, schemas: restaurantRegistry() });
    const GSTIN = "33AAAAA0000A1Z5";
    for (const e of ["check", "bill"]) expect(restaurantRegistry().get(e)!.pii).toContain("customer_gstin");
    await a.engine.recordMuts("check.create", check("c1", { order_type: "dine_in", status: "open", customer_gstin: GSTIN }));
    await a.engine.recordMuts("bill.customer_details.edit", [{ e: "bill", id: "b1", k: "insert", f: { customer_gstin: GSTIN, customer_name: NAME } }]);
    await w.syncDevice(a);
    await w.syncDevice(rx);
    expect(JSON.stringify(await rx.store.list("check"))).toContain(GSTIN);
    await w.cloud.erasePii({ origin: "devA", stream: OUTLET, seq: 1 });
    await w.cloud.erasePii({ origin: "devA", stream: OUTLET, seq: 2 });
    await w.syncDevice(rx);
    await w.syncDevice(a);
    for (const d of [a, rx]) {
      const text = JSON.stringify([await d.store.list("check"), await d.store.list("bill"), await d.store.list(T.op)]);
      expect(text).not.toContain(GSTIN);
      expect(text).not.toContain(NAME);
    }
  });
});
